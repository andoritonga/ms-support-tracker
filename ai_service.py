import os
import json
import urllib.request
import urllib.error
from typing import List, Dict, Any, Optional

GEMINI_MODELS = [
    "gemini-2.5-flash",
    "gemini-1.5-flash"
]

def get_api_key(override_key: Optional[str] = None) -> str:
    if override_key and override_key.strip():
        return override_key.strip()
    return os.getenv("GEMINI_API_KEY", "").strip()

def call_gemini(prompt: str, api_key: str, system_instruction: Optional[str] = None) -> str:
    """Call Google Gemini API via REST"""
    if not api_key:
        raise ValueError(
            "Gemini API key is required. Please set GEMINI_API_KEY in .env or provide it in the UI."
        )

    last_error = None
    for model in GEMINI_MODELS:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={api_key}"
        
        contents = []
        if system_instruction:
            contents.append({
                "role": "user",
                "parts": [{"text": f"System Instructions: {system_instruction}"}]
            })
            contents.append({
                "role": "model",
                "parts": [{"text": "Understood. I will strictly follow these instructions."}]
            })

        contents.append({
            "role": "user",
            "parts": [{"text": prompt}]
        })

        payload = {
            "contents": contents,
            "generationConfig": {
                "temperature": 0.3,
                "topP": 0.85,
                "maxOutputTokens": 2048
            }
        }

        req = urllib.request.Request(
            url,
            data=json.dumps(payload).encode("utf-8"),
            headers={"Content-Type": "application/json"},
            method="POST"
        )

        try:
            with urllib.request.urlopen(req, timeout=45) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                candidates = data.get("candidates", [])
                if candidates:
                    parts = candidates[0].get("content", {}).get("parts", [])
                    if parts:
                        return parts[0].get("text", "")
                return "No content generated by Gemini."
        except urllib.error.HTTPError as e:
            err_body = e.read().decode("utf-8")
            last_error = f"HTTP {e.code} ({model}): {err_body}"
            # If model not found or quota, try next model
            continue
        except Exception as e:
            last_error = f"Error calling {model}: {e}"
            continue

    raise RuntimeError(last_error or "Failed to call Gemini API.")

def generate_executive_summary(activities: List[Dict[str, Any]], period_str: str, api_key: str) -> str:
    """Generate professional executive summary of operations and incidents"""
    if not activities:
        return "No activity logs available for the selected period."

    # Prepare concise summary metrics
    total = len(activities)
    closed = sum(1 for a in activities if a.get("status") == "Closed")
    in_progress = total - closed
    total_mins = sum(a.get("durationMinutes") or 0 for a in activities)
    total_hours = round(total_mins / 60, 1)

    # Summarize per customer
    customer_counts = {}
    service_counts = {}
    category_counts = {}
    sample_issues = []

    for a in activities:
        cust = a.get("customer") or "Unknown"
        customer_counts[cust] = customer_counts.get(cust, 0) + 1

        svc = a.get("services") or "Other"
        service_counts[svc] = service_counts.get(svc, 0) + 1

        cat = a.get("category") or "Other"
        category_counts[cat] = category_counts.get(cat, 0) + 1

        # Keep notable issues and root causes
        if a.get("category") == "Issue" or a.get("rootCause"):
            sample_issues.append({
                "customer": cust,
                "task": a.get("taskDescription"),
                "root_cause": a.get("rootCause"),
                "solution": a.get("solution"),
                "duration": a.get("duration")
            })

    # Limit sample issues to prevent token bloat
    sample_issues_subset = sample_issues[:25]

    prompt = f"""
You are the Lead Managed Services Operations Consultant and Cloud Reliability Engineer.
Analyze the following operational support activity dataset for the period: **{period_str}**.

### Operational Metrics:
- **Total Logged Activities**: {total}
- **Resolved / Closed**: {closed} ({round(closed/total*100 if total else 0)}%)
- **In Progress / Pending**: {in_progress}
- **Total Support Hours**: {total_hours} hours ({total_mins} minutes)
- **Customer Activity Volume**: {json.dumps(customer_counts)}
- **Cloud Services Distribution**: {json.dumps(service_counts)}
- **Category Breakdown**: {json.dumps(category_counts)}

### Sample Incidents, Root Causes & Resolutions:
{json.dumps(sample_issues_subset, indent=2)}

### Your Task:
Write an authoritative, high-impact **Executive Operations & Incident Summary Report** in Markdown format suitable for CXOs and engineering leads.
Include the following structured sections:

1. **📊 Executive Synthesis**: High-level summary of operational stability, workload volume, and key achievements during this period.
2. **🔍 Critical Incident & Root Cause Analysis**: Identify common patterns, infrastructure bottlenecks (e.g. Compute Engine VM issues, network quotas, configuration drift, SSL/TLS), and why they occurred.
3. **🏢 Key Account Breakdown**: Brief summary of support delivered for top customers (highlighting high-volume clients).
4. **💡 Strategic & Preventative Recommendations**: 3 to 4 concrete engineering actions (automation, alerting, capacity planning, cost optimization) to reduce recurring issues.

Write in a professional, clear, and confident technical tone with crisp markdown formatting (tables, bullet points, and bold highlights).
"""

    system_instruction = "You are a senior Managed Services Cloud Infrastructure Director. Produce polished, executive-ready technical reports."
    return call_gemini(prompt, api_key, system_instruction)

def polish_activity_notes(task_desc: str, root_cause: str, solution: str, api_key: str) -> Dict[str, str]:
    """Refine rough engineer notes into professional client-ready descriptions"""
    prompt = f"""
You are a Cloud Managed Services Technical Writer. Refine the following support engineer notes into clean, professional, client-ready language.

Input Notes:
- Task Description: {task_desc or "(empty)"}
- Root Cause: {root_cause or "(empty)"}
- Solution: {solution or "(empty)"}

Requirements:
- Preserve all technical facts (commands, service names, IP, IDs, error messages).
- Enhance clarity, tone, and grammar.
- Keep each field concise yet thorough.
- Return ONLY a valid JSON object with the exact keys: "taskDescription", "rootCause", "solution". Do not include markdown fences or other text.
"""
    response_text = call_gemini(prompt, api_key)
    # Parse JSON
    try:
        clean_text = response_text.strip()
        if clean_text.startswith("```"):
            clean_text = clean_text.split("\n", 1)[-1].rsplit("```", 1)[0].strip()
        data = json.loads(clean_text)
        return {
            "taskDescription": data.get("taskDescription", task_desc),
            "rootCause": data.get("rootCause", root_cause),
            "solution": data.get("solution", solution)
        }
    except Exception:
        return {
            "taskDescription": task_desc,
            "rootCause": root_cause,
            "solution": solution
        }
